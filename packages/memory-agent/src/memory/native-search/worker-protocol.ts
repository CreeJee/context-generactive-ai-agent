import { Schema } from "effect";
import { Rpc, RpcGroup } from "effect/rpc";
import { NativeReadInput, NativeReadOutput, TransferredVector } from "./read-protocol.ts";

// Only the owner transport uses these low-level commands. Public high-level search never
// sends a candidate allowlist; its separate request contract is in contracts.ts.
const correlation = { requestId: Schema.String, epoch: Schema.String };
// Host commands carry owned copies, so the worker receives their buffers instead of a clone.
const vector = TransferredVector;
const ids = Schema.Array(Schema.String);

export const OwnerSetup = Schema.Struct({
  kind: Schema.Literal("setup"),
  epoch: Schema.String,
  dimensions: Schema.Int,
  bits: Schema.Int,
  cacheDirectory: Schema.String,
  /** Private transport binding, generated by the host; not a caller-supplied capability. */
  ownerKey: Schema.optional(Schema.String),
  /** Host-owned, trusted file path; never supplied by a search request. */
  databasePath: Schema.optional(Schema.String),
  recover: Schema.optional(Schema.Boolean),
});
export type OwnerSetup = typeof OwnerSetup.Type;

export const OwnerCommand = Schema.TaggedUnion({
  add: { ...correlation, vectors: vector, ids },
  /** One owner step for the whole batch, like add: no other command interleaves inside it. */
  remove: { ...correlation, ids },
  save: { ...correlation },
  reset: { ...correlation },
  validate: { ...correlation, ids },
  "vector-search": {
    ...correlation,
    query: vector,
    k: Schema.Int,
    allowedIds: Schema.optional(ids),
  },
  "vector-search-controlled": {
    ...correlation,
    query: vector,
    k: Schema.Int,
    allowedIds: ids,
    /** Set only by host dispatch; user values are never adopted. */
    controlToken: Schema.optional(Schema.String),
    budgetMs: Schema.Finite.check(Schema.makeFilter((value) => value >= 0 && value <= 2_000)),
  },
  "memory-search": {
    ...correlation,
    input: NativeReadInput,
    /** Set only by host dispatch; user values are never adopted. */
    controlToken: Schema.optional(Schema.String),
  },
});
export type OwnerCommand = typeof OwnerCommand.Type;

export const OwnerReply = Schema.TaggedUnion({
  ack: { ...correlation, size: Schema.Int },
  removed: {
    ...correlation,
    /** How many of the requested ids were present. */
    removed: Schema.Int,
    size: Schema.Int,
  },
  "vector-hits": {
    ...correlation,
    ids,
    scores: Schema.Array(Schema.Finite),
    size: Schema.Int,
    /** Monotonic worker window around the synchronous native call, no user data. */
    workerCpuUs: Schema.optional(Schema.Finite),
    nativeWindow: Schema.optional(Schema.Struct({ startNs: Schema.String, endNs: Schema.String })),
  },
  "controlled-result": {
    ...correlation,
    outcome: Schema.Literals([
      "success",
      "cancelled",
      "budget-exceeded",
      "invalid-input",
      "index-failed",
    ]),
    ids,
    scores: Schema.Array(Schema.Finite),
    size: Schema.Int,
    nativeMs: Schema.Finite,
  },
  "memory-result": {
    ...correlation,
    result: NativeReadOutput,
    workerCpuUs: Schema.optional(Schema.Finite),
  },
});
export type OwnerReply = typeof OwnerReply.Type;

export class NativeOwnerFailed extends Schema.TaggedError<NativeOwnerFailed>()(
  "NativeOwnerFailed",
  {
    reason: Schema.Literals([
      "invalid-input",
      "queue-full",
      "input-budget",
      "worker-exit",
      "worker-error",
      "startup-timeout",
      "request-timeout",
      "closed",
      "epoch-mismatch",
      "index-failed",
      "lease-unavailable",
      "read-failed",
      "native-incompatible",
    ]),
    /** The native exception, kept inside the process that caught it; IPC carries only `reason`. */
    cause: Schema.optional(Schema.Defect()),
  },
) {
  override get message() {
    return this.reason === "lease-unavailable"
      ? "Vector index is held by another process using the same storage root"
      : `Native search owner failed: ${this.reason}`;
  }
}

/** What a started owner reports before it takes commands. */
export const OwnerReady = Schema.Struct({
  threadId: Schema.Int,
  size: Schema.Int,
  needsReset: Schema.Boolean,
});
export type OwnerReady = typeof OwnerReady.Type;

/** Waits for the owner's setup; its failure is the reason the owner could not start. */
export const Open = Rpc.make("Open", { success: OwnerReady, error: NativeOwnerFailed });
export const Execute = Rpc.make("Execute", {
  payload: OwnerCommand,
  success: OwnerReply,
  error: NativeOwnerFailed,
});
export const NativeOwnerRpcs = RpcGroup.make(Open, Execute);
