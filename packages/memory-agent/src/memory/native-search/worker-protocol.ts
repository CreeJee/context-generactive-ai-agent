import { Schema } from "effect";
import { NativeReadInput, NativeReadOutput } from "./read-protocol.ts";

// Only the owner transport uses these low-level commands. Public high-level search never
// sends a candidate allowlist; its separate request contract is in contracts.ts.
const correlation = { requestId: Schema.String, epoch: Schema.String };
const vector = Schema.instanceOf(Float32Array);
const ids = Schema.Array(Schema.String);

export const OwnerSetup = Schema.Struct({
  kind: Schema.Literal("setup"),
  epoch: Schema.String,
  dimensions: Schema.Int,
  bits: Schema.Int,
  cacheDirectory: Schema.String,
  /** Private transport binding, generated by the host; not a caller-supplied capability. */
  ownerKey: Schema.optional(Schema.String),
  /** Host-owned, trusted file path; never supplied by a search request. */
  databasePath: Schema.optional(Schema.String),
  recover: Schema.optional(Schema.Boolean),
});
export type OwnerSetup = typeof OwnerSetup.Type;

export const OwnerCommand = Schema.Union([
  Schema.Struct({ kind: Schema.Literal("add"), ...correlation, vectors: vector, ids }),
  /** One owner step for the whole batch, like add: no other command interleaves inside it. */
  Schema.Struct({ kind: Schema.Literal("remove"), ...correlation, ids }),
  Schema.Struct({ kind: Schema.Literal("save"), ...correlation }),
  Schema.Struct({ kind: Schema.Literal("reset"), ...correlation }),
  Schema.Struct({ kind: Schema.Literal("validate"), ...correlation, ids }),
  Schema.Struct({
    kind: Schema.Literal("vector-search"),
    ...correlation,
    query: vector,
    k: Schema.Int,
    allowedIds: Schema.optional(ids),
  }),
  Schema.Struct({
    kind: Schema.Literal("vector-search-controlled"),
    ...correlation,
    query: vector,
    k: Schema.Int,
    allowedIds: ids,
    /** Set only by host dispatch; user values are never adopted. */
    controlToken: Schema.optional(Schema.String),
    budgetMs: Schema.Finite.check(Schema.makeFilter((value) => value >= 0 && value <= 2_000)),
  }),
  Schema.Struct({
    kind: Schema.Literal("memory-search"),
    ...correlation,
    input: NativeReadInput,
    /** Set only by host dispatch; user values are never adopted. */
    controlToken: Schema.optional(Schema.String),
  }),
  Schema.Struct({ kind: Schema.Literal("close"), ...correlation }),
]);
export type OwnerCommand = typeof OwnerCommand.Type;

export const OwnerReply = Schema.Union([
  Schema.Struct({
    kind: Schema.Literal("ready"),
    epoch: Schema.String,
    threadId: Schema.Int,
    needsReset: Schema.optional(Schema.Boolean),
    size: Schema.Int,
  }),
  Schema.Struct({ kind: Schema.Literal("ack"), ...correlation, size: Schema.Int }),
  Schema.Struct({
    kind: Schema.Literal("removed"),
    ...correlation,
    /** How many of the requested ids were present. */
    removed: Schema.Int,
    size: Schema.Int,
  }),
  Schema.Struct({
    kind: Schema.Literal("vector-hits"),
    ...correlation,
    ids,
    scores: Schema.Array(Schema.Finite),
    size: Schema.Int,
    /** Monotonic worker window around the synchronous native call, no user data. */
    workerCpuUs: Schema.optional(Schema.Finite),
    nativeWindow: Schema.optional(Schema.Struct({ startNs: Schema.String, endNs: Schema.String })),
  }),
  Schema.Struct({
    kind: Schema.Literal("controlled-result"),
    ...correlation,
    outcome: Schema.Literals([
      "success",
      "cancelled",
      "budget-exceeded",
      "invalid-input",
      "index-failed",
    ]),
    ids,
    scores: Schema.Array(Schema.Finite),
    size: Schema.Int,
    nativeMs: Schema.Finite,
  }),
  Schema.Struct({
    kind: Schema.Literal("memory-result"),
    ...correlation,
    result: NativeReadOutput,
    workerCpuUs: Schema.optional(Schema.Finite),
  }),
  Schema.Struct({ kind: Schema.Literal("closed"), ...correlation }),
  Schema.Struct({
    kind: Schema.Literal("failed"),
    ...correlation,
    code: Schema.Literals([
      "invalid-input",
      "lease-unavailable",
      "read-failed",
      "native-incompatible",
      "index-failed",
      "epoch-mismatch",
      "closed",
    ]),
  }),
]);
export type OwnerReply = typeof OwnerReply.Type;

export class NativeOwnerFailed extends Schema.TaggedError<NativeOwnerFailed>()(
  "NativeOwnerFailed",
  {
    reason: Schema.Literals([
      "invalid-input",
      "queue-full",
      "input-budget",
      "worker-exit",
      "worker-error",
      "startup-timeout",
      "request-timeout",
      "closed",
      "epoch-mismatch",
      "index-failed",
      "lease-unavailable",
      "read-failed",
      "native-incompatible",
    ]),
  },
) {
  override get message() {
    switch (this.reason) {
      case "lease-unavailable":
        return "Vector index is held by another process using the same storage root";
      default:
        return `Native search owner failed: ${this.reason}`;
    }
  }
}
