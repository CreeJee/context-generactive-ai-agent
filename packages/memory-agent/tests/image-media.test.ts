import { Schema } from "effect";
import { it as effectTest } from "@effect/vitest";
import { Crypto, Effect, Result } from "effect";
import { withTestPlatform } from "./support/platform.ts";
import {
  ImageExecutorModel,
  DirectImageExecutionFailed,
  ImageMediaApprovalRequired,
  ImageMediaExecutionFailed,
  ImageMediaUnavailable,
  makeImageMediaWorkflow,
  type ImageFeatureApi,
  ImageRerouteConfirmation,
  ImageRouteDecision,
  type ImageRouterApi,
} from "memory-agent";
import { describe, expect } from "vite-plus/test";

const decision: ImageRouteDecision = ImageRouteDecision.selected({
  mode: "auto",
  preference: "balanced",
  initiatorChatRouteId: "chat:anthropic:claude-test",
  initiatorChatModel: "claude-test",
  executorMediaRouteId: "media:openai:direct_adapter:gpt-image-2",
  executorMediaModel: ImageExecutorModel.explicit({ model: "gpt-image-2" }),
  provider: "openai",
  initiatorProvider: "openai",
  crossProvider: false,
  crossProviderConsentMode: "always",
  crossProviderApprovalRequired: false,
  accountId: "account-1",
  executionMode: "direct_adapter",
  estimatedCostUsd: 0.1,
  score: 1,
  reasons: ["fixture"],
  ranking: [],
});
const feature: ImageFeatureApi = {
  status: Effect.succeed({ imageGenerationEnabled: true }),
  setImageGenerationEnabled: () => Effect.die("unused"),
};
const router: ImageRouterApi = {
  select: () => Effect.succeed(decision),
  rerouteAfterFailure: (failedDecision, reason) =>
    Effect.succeed(
      ImageRerouteConfirmation.confirmation_required({ failedDecision, reason, alternatives: [] }),
    ),
};
const request = {
  initiatorChatRouteId: decision.initiatorChatRouteId,
  prompt: "a small blue bird",
  approved: true,
};

function attachmentStore(saved: Uint8Array[]) {
  return {
    save: (bytes: Uint8Array) => {
      saved.push(bytes);
      return Effect.succeed({
        id: "a".repeat(64),
        mimeType: "image/png" as const,
        bytes: bytes.byteLength,
        createdAt: "2026-09-20T00:00:00.000Z",
      });
    },
  };
}

describe("ImageMediaWorkflow", () => {
  effectTest.effect("requires explicit approval before paid execution", () =>
    Effect.gen(function* () {
      let executions = 0;
      const workflow = makeImageMediaWorkflow({
        feature: feature,
        router: router,
        executor: {
          generate: () => {
            executions += 1;
            return Effect.die("must not execute");
          },
        },
        attachments: attachmentStore([]),
        crypto: yield* Crypto.Crypto,
      });
      const result = yield* Effect.result(workflow.generate({ ...request, approved: false }));
      expect(Result.isFailure(result) && result.failure).toBeInstanceOf(ImageMediaApprovalRequired);
      expect(executions).toBe(0);
    }).pipe(withTestPlatform),
  );

  effectTest.effect(
    "persists generated bytes and returns provenance without embedding base64",
    () =>
      Effect.gen(function* () {
        const bytes = Uint8Array.from([137, 80, 78, 71, 13, 10, 26, 10]);
        const saved: Uint8Array[] = [];
        const workflow = makeImageMediaWorkflow({
          feature: feature,
          router: router,
          executor: {
            generate: () =>
              Effect.succeed({
                bytes,
                contentType: "image/png",
                providerRequestId: "request-1",
                usage: { outputTokens: 42 },
              }),
          },
          attachments: attachmentStore(saved),
          crypto: yield* Crypto.Crypto,
        });
        const asset = yield* workflow.generate(request);
        expect(saved).toEqual([bytes]);
        expect(asset).toMatchObject({
          initiatorChatModel: "claude-test",
          executorMediaRouteId: decision.executorMediaRouteId,
          executorMediaModel: ImageExecutorModel.explicit({ model: "gpt-image-2" }),
          executionMode: "direct_adapter",
          estimatedCostUsd: 0.1,
          providerRequestId: "request-1",
          usage: { outputTokens: 42 },
        });
        expect(
          yield* Schema.encodeEffect(Schema.fromJsonString(Schema.Unknown))(asset),
        ).not.toContain("base64");
      }).pipe(withTestPlatform),
  );

  effectTest.effect(
    "binds one-time cross-provider approval and revalidates consent before execution",
    () =>
      Effect.gen(function* () {
        const crossDecision: ImageRouteDecision = {
          ...decision,
          initiatorProvider: "anthropic",
          crossProvider: true,
          crossProviderConsentMode: "ask",
          crossProviderApprovalRequired: true,
        };
        let mode: "disabled" | "ask" | "always" = "ask";
        let executions = 0;
        const workflow = makeImageMediaWorkflow({
          feature: feature,
          router: { ...router, select: () => Effect.succeed(crossDecision) },
          executor: {
            generate: () => {
              executions += 1;
              return Effect.succeed({ bytes: Uint8Array.of(1), contentType: "image/png" });
            },
          },
          attachments: attachmentStore([]),
          crypto: yield* Crypto.Crypto,
          catalog: undefined,
          crossProviderConsent: {
            read: Effect.succeed({ version: 1, pairs: {} }),
            decide: (pair) =>
              Effect.succeed({
                ...pair,
                crossProvider: true,
                mode,
                allowedWithoutPrompt: mode === "always",
                requiresApproval: mode === "ask",
                reasons: [],
                settingsVersion: 1,
              }),
            set: () => Effect.die("unused"),
          },
        });
        const first = yield* Effect.result(workflow.generate(request));
        const required = Result.isFailure(first) && first.failure;
        expect(required).toBeInstanceOf(ImageMediaApprovalRequired);
        expect(required).toMatchObject({ reason: "cross_provider" });
        if (!Schema.is(ImageMediaApprovalRequired)(required)) return;
        const approval = required.approval!;
        yield* workflow.generate({
          ...request,
          runId: approval.runId,
          crossProviderApproval: approval,
        });
        expect(executions).toBe(1);
        const wrong = yield* Effect.result(
          workflow.generate({
            ...request,
            runId: approval.runId,
            crossProviderApproval: { ...approval, executorMediaRouteId: "tampered" },
          }),
        );
        expect(Result.isFailure(wrong) && wrong.failure).toBeInstanceOf(ImageMediaApprovalRequired);
        mode = "disabled";
        const revoked = yield* Effect.result(
          workflow.generate({ ...request, runId: approval.runId, crossProviderApproval: approval }),
        );
        const unavailable = Result.isFailure(revoked) && revoked.failure;
        expect(unavailable).toBeInstanceOf(ImageMediaUnavailable);
        expect(unavailable).toMatchObject({ reason: "consent_disabled" });
        expect(executions).toBe(1);
      }).pipe(withTestPlatform),
  );

  effectTest.effect("returns confirmation-required reroute evidence after execution failure", () =>
    Effect.gen(function* () {
      const workflow = makeImageMediaWorkflow({
        feature: feature,
        router: router,
        executor: {
          generate: () =>
            Effect.fail(DirectImageExecutionFailed.make({ reason: "provider_rejected" })),
        },
        attachments: attachmentStore([]),
        crypto: yield* Crypto.Crypto,
      });
      const result = yield* Effect.result(workflow.generate(request));
      const failed = Result.isFailure(result) && result.failure;
      expect(failed).toBeInstanceOf(ImageMediaExecutionFailed);
      const reroute = Schema.is(ImageMediaExecutionFailed)(failed) ? failed.reroute : undefined;
      expect(ImageRerouteConfirmation.$is("confirmation_required")(reroute)).toBe(true);
      expect(failed).toMatchObject({ reroute: { alternatives: [] } });
    }).pipe(withTestPlatform),
  );
});
